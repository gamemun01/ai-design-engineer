#!/usr/bin/env node
'use strict';

const fs = require('node:fs');
const path = require('node:path');
const { parseFrontmatter } = require('../tests/lib/contract-checks');
const { checkLocalLinks } = require('./lib/skill-integrity');

const marker = '<!-- Generated by scripts/register-codex-skills.js; edit canonical source instead. -->';
const uiMarker = '# Generated by scripts/register-codex-skills.js; edit generator instead.';
const repoRoot = path.resolve(__dirname, '..');
const interfaces = {
  'prompt-context-loading': ['Load Context', 'Load repo rules and route the task to the right skill', 'load repository context and select the relevant task skill'],
  'core-system-prompt': ['Core Baseline', 'Establish design engineering rules and quality standards', 'establish the design engineering baseline for this task'],
  'ux-decision-framework': ['UX Decisions', 'Plan user journeys, task flows, and UX decisions', 'plan the user journey and UX decisions from my product brief'],
  'project-design-advisor': ['Project Design Advisor', 'Shape ideas, assess design readiness, handoffs and changes', 'help design my project from its idea or assess the supplied baseline, keeping proposals and approval evidence separate'],
  'ui-generation-structured': ['UI Generation', 'Generate branded UI prompts with the eight-layer framework', 'create an eight-layer UI prompt from my approved UX brief'],
  'design-system-governance': ['Design System', 'Audit tokens, components, and design system consistency', 'audit my component against the existing design system'],
  'code-generation': ['Generate Code', 'Implement approved UI in the installed frontend stack', 'implement the approved UI using the existing project stack'],
  'review-critique': ['Review & Critique', 'Review UI and code with evidence and readiness limits', 'review the supplied UI or source with evidence-backed findings'],
  'refinement-workflow': ['Refine Findings', 'Fix prioritized review findings and verify the changes', 'fix the prioritized review findings and verify the changes'],
  'anti-patterns-detector': ['Detect Anti-Patterns', 'Find recurring design, code, and workflow anti-patterns', 'audit the supplied artifact for recurring anti-patterns'],
  'multi-agent-workflow': ['Workflow Plan', 'Plan scoped agent roles and explicit artifact handoffs', 'plan scoped roles and handoffs for this workflow'],
  'a11y-deep-audit': ['Accessibility Audit', 'Audit keyboard, semantics, contrast, and WCAG evidence', 'audit accessibility of the supplied source or running UI'],
  'motion-choreography': ['Motion Design', 'Specify motion tokens and reduced-motion alternatives', 'specify motion with tokens and reduced-motion alternatives'],
};

function sources(root) {
  const files = [];
  function visit(dir) {
    if (!fs.existsSync(dir)) return;
    for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
      if (entry.name === 'deprecated') continue;
      const file = path.join(dir, entry.name);
      if (entry.isDirectory()) visit(file);
      else if (entry.name === 'SKILL.md') files.push(file);
    }
  }
  visit(path.join(root, 'skills'));
  visit(path.join(root, 'plugins', 'community'));
  return files.sort();
}

function relativeLink(from, target) {
  return path.relative(path.dirname(from), target).split(path.sep).join('/');
}

function createPlan(root) {
  const seen = new Set();
  return sources(root).map((source) => {
    const parsed = parseFrontmatter(fs.readFileSync(source, 'utf8'));
    const yaml = parsed.yaml;
    if (parsed.error || !yaml || typeof yaml.name !== 'string' || typeof yaml.description !== 'string') {
      throw new Error(`Invalid source metadata: ${source}`);
    }
    if (!/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(yaml.name) || yaml.name.length > 64 || yaml.description.length > 1024) {
      throw new Error(`Invalid native name/description: ${source}`);
    }
    if (seen.has(yaml.name)) throw new Error(`Duplicate source name: ${yaml.name}`);
    seen.add(yaml.name);
    const file = path.join(root, '.agents', 'skills', yaml.name, 'SKILL.md');
    const link = relativeLink(file, source);
    const content = [
      '---',
      `name: ${yaml.name}`,
      `description: ${JSON.stringify(yaml.description)}`,
      '---',
      '',
      marker,
      '',
      `# ${yaml.name}`,
      '',
      `Read the [canonical skill](${link}) before performing the requested task.`,
      'Resolve this link relative to this SKILL.md file, not the working directory.',
      'Follow the canonical workflow and read its supporting references only when',
      'relevant. Resolve those references relative to the canonical source file.',
      '',
      `Use [AGENTS.md](${relativeLink(file, path.join(root, 'AGENTS.md'))}) for repository rules`,
      `and [INDEX.md](${relativeLink(file, path.join(root, 'skills', 'INDEX.md'))}) for routing.`,
      'Retain already-loaded context. Host instructions and the user\'s authorized',
      'scope take priority; this pointer grants no additional permissions.',
      '',
    ].join('\n');
    const [title, description, task] = interfaces[yaml.name] || [yaml.name, 'Apply this repository skill to the requested task', 'help with the requested task'];
    const uiFile = path.join(path.dirname(file), 'agents', 'openai.yaml');
    const uiContent = [
      uiMarker,
      'interface:',
      `  display_name: ${JSON.stringify(`AIDE ${title}`)}`,
      `  short_description: ${JSON.stringify(description)}`,
      `  default_prompt: ${JSON.stringify(`Use $${yaml.name} to ${task}.`)}`,
      '',
    ].join('\n');
    return { name: yaml.name, source, file, content, uiFile, uiContent };
  });
}

function ensureSafeDestination(root, file) {
  const relative = path.relative(root, file);
  if (relative.startsWith('..') || path.isAbsolute(relative)) throw new Error('Destination leaves repository');
  let current = root;
  for (const segment of relative.split(path.sep)) {
    current = path.join(current, segment);
    if (fs.existsSync(current) && fs.lstatSync(current).isSymbolicLink()) {
      throw new Error(`Refusing redirected destination: ${current}`);
    }
  }
}

function register(root, mode) {
  const plan = createPlan(root);
  if (!plan.length) throw new Error('No active skills found');
  // Preflight the entire batch before any write; never replace a user's skill.
  for (const entry of plan) {
    for (const [file, content, managedMarker] of [[entry.file, entry.content, marker], [entry.uiFile, entry.uiContent, uiMarker]]) {
      ensureSafeDestination(root, file);
      if (fs.existsSync(file)) {
        const existing = fs.readFileSync(file, 'utf8');
        if (!existing.includes(managedMarker)) throw new Error(`Unmanaged skill file already exists: ${file}`);
        if (mode === 'check' && existing.replace(/\r\n/g, '\n') !== content) throw new Error(`Stale native pointer or UI metadata: ${entry.name}`);
      } else if (mode === 'check') throw new Error(`Native skill file missing: ${file}`);
    }
  }
  for (const entry of plan) {
    if (mode === 'write') {
      fs.mkdirSync(path.dirname(entry.file), { recursive: true });
      fs.writeFileSync(entry.file, entry.content, 'utf8');
      fs.mkdirSync(path.dirname(entry.uiFile), { recursive: true });
      fs.writeFileSync(entry.uiFile, entry.uiContent, 'utf8');
    }
    if (mode !== 'dry-run') {
      const errors = checkLocalLinks(entry.file, root);
      if (errors.length) throw new Error(`${entry.name}: ${errors.join('; ')}`);
    }
  }
  return plan;
}

if (require.main === module) {
  const args = process.argv.slice(2);
  const modes = { '--dry-run': 'dry-run', '--write': 'write', '--check': 'check' };
  if (args.length !== 1 || !modes[args[0]]) {
    console.error('Usage: node scripts/register-codex-skills.js --dry-run|--write|--check');
    process.exitCode = 1;
  } else {
    try {
      const plan = register(repoRoot, modes[args[0]]);
      plan.forEach(({ name }) => console.log(`  ${name}`));
      console.log(`${plan.length} native skill pointers: ${modes[args[0]]} OK`);
    } catch (error) {
      console.error(error.message);
      process.exitCode = 1;
    }
  }
}

module.exports = { createPlan, register, ensureSafeDestination };
